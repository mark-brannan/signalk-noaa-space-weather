#!/usr/bin/env node
/**
 * Writes public/coastline.js from Natural Earth's 110m coastline. Run by hand
 * when the source data changes, which is roughly never; the output is
 * committed. Deliberately not wired to prebuild or prepare the way
 * scripts/sync-icon.mjs is -- this one needs the network, and the registry
 * scores this package offline.
 *
 *   node scripts/gen-coastline.mjs
 *
 * Natural Earth is public domain (naturalearthdata.com/about/terms-of-use),
 * which is why it is the source rather than one of the prettier datasets.
 *
 * The simplification is tuned to the coarsest thing that draws it: D-RAP's
 * grid is 2 degrees of latitude by 4 of longitude, so a coastline held to a
 * quarter degree is already finer than any cell it annotates. Everything
 * below is chosen to keep the asset small enough that its size never becomes
 * an argument -- see the measurements on
 * https://github.com/mark-brannan/signalk-noaa-space-weather/issues/32
 */
import { writeFileSync } from 'node:fs'

const SOURCE =
  'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_coastline.geojson'

/** Douglas-Peucker tolerance, degrees. */
const TOLERANCE = 0.25
/** Coordinates are stored to this many decimal places. */
const PRECISION = 1
/** Rings whose bounding box is smaller than this, in degrees, are dropped. */
const MIN_EXTENT = 1

function rings(geojson) {
  const out = []
  const walk = (geometry) => {
    if (!geometry) return
    switch (geometry.type) {
      case 'LineString':
        out.push(geometry.coordinates)
        break
      case 'MultiLineString':
      case 'Polygon':
        geometry.coordinates.forEach((ring) => out.push(ring))
        break
      case 'MultiPolygon':
        geometry.coordinates.forEach((polygon) =>
          polygon.forEach((ring) => out.push(ring))
        )
        break
    }
  }
  geojson.features.forEach((feature) => walk(feature.geometry))
  return out
}

function perpendicularDistance(point, start, end) {
  const px = point[0] - start[0]
  const py = point[1] - start[1]
  const dx = end[0] - start[0]
  const dy = end[1] - start[1]
  const lengthSquared = dx * dx + dy * dy
  if (lengthSquared === 0) return Math.hypot(px, py)
  const t = Math.max(0, Math.min(1, (px * dx + py * dy) / lengthSquared))
  return Math.hypot(px - t * dx, py - t * dy)
}

function simplify(points, tolerance) {
  if (points.length < 3) return points
  let furthest = 0
  let index = 0
  for (let i = 1; i < points.length - 1; i++) {
    const distance = perpendicularDistance(
      points[i],
      points[0],
      points[points.length - 1]
    )
    if (distance > furthest) {
      furthest = distance
      index = i
    }
  }
  if (furthest <= tolerance) return [points[0], points[points.length - 1]]
  return simplify(points.slice(0, index + 1), tolerance)
    .slice(0, -1)
    .concat(simplify(points.slice(index), tolerance))
}

function extent(ring) {
  let west = 180
  let east = -180
  let south = 90
  let north = -90
  for (const [lon, lat] of ring) {
    if (lon < west) west = lon
    if (lon > east) east = lon
    if (lat < south) south = lat
    if (lat > north) north = lat
  }
  return Math.max(east - west, north - south)
}

/**
 * Google's polyline varint, over deltas between successive fixed-point
 * coordinates. Chosen over a JSON array of numbers because it is a fifth of
 * the size for the same shape (34 KB against 7 KB), and the decoder is nine
 * lines.
 */
function varint(value) {
  let bits = value < 0 ? ~(value << 1) : value << 1
  let encoded = ''
  while (bits >= 0x20) {
    encoded += String.fromCharCode((0x20 | (bits & 0x1f)) + 63)
    bits >>= 5
  }
  return encoded + String.fromCharCode(bits + 63)
}

function encode(ring) {
  const scale = Math.pow(10, PRECISION)
  let previousLon = 0
  let previousLat = 0
  let encoded = ''
  for (const [lon, lat] of ring) {
    const x = Math.round(lon * scale)
    const y = Math.round(lat * scale)
    encoded += varint(x - previousLon) + varint(y - previousLat)
    previousLon = x
    previousLat = y
  }
  return encoded
}

const response = await fetch(SOURCE)
if (!response.ok) throw new Error(`${SOURCE} responded ${response.status}`)
const simplified = rings(await response.json())
  .filter((ring) => extent(ring) >= MIN_EXTENT)
  .map((ring) => simplify(ring, TOLERANCE))
  .filter((ring) => ring.length >= 2)

const lines = simplified.map(encode)
const points = simplified.reduce((total, ring) => total + ring.length, 0)
const body = lines.map((line) => JSON.stringify(line)).join(',\n  ')
const target = new URL('../public/coastline.js', import.meta.url)

writeFileSync(
  target,
  `// Generated by scripts/gen-coastline.mjs -- do not edit by hand.\n` +
    `// Natural Earth 110m coastline (public domain), simplified to\n` +
    `// ${TOLERANCE} degrees and stored to ${PRECISION} decimal place as\n` +
    `// delta-encoded polyline varints. One string per ring; public/geo.js\n` +
    `// decodes them.\n` +
    `export const COASTLINE = [\n  ${body}\n]\n`
)

process.stderr.write(
  `${lines.length} rings, ${points} points, ` +
    `${Buffer.byteLength(lines.join(''))} encoded bytes\n`
)
